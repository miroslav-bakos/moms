'use strict';
// Run against a temporary database; never write to the application's database.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {Pool}=require('pg');
const {config}=require('../src/config');
const original=require('../src/db');
const admin=new Pool({connectionString:config.databaseUrl});
const database='moms_inventory_test_'+crypto.randomBytes(8).toString('hex');
let pool;
(async()=>{
  await admin.query(`CREATE DATABASE ${database}`);
  const url=new URL(config.databaseUrl);url.pathname='/'+database;
  pool=new Pool({connectionString:url.toString()});
  for(const file of fs.readdirSync(path.join(__dirname,'../migrations')).filter(f=>f.endsWith('.sql')).sort()) await pool.query(fs.readFileSync(path.join(__dirname,'../migrations',file),'utf8'));
  require.cache[require.resolve('../src/db')].exports={query:pool.query.bind(pool),withClient:async fn=>{const client=await pool.connect();try{return await fn(client);}finally{client.release();}}};
  const service=require(process.env.INVENTORY_SERVICE_PATH || '../src/services/inventory');
  const first=await service.saveMaterial(null,{name:'Paper',unit:'A4',stock:'10',manufacturer:'  Acme  ',purchase_url:'https://example.com/paper?a=1&b=2'});
  const second=await service.saveMaterial(null,{name:'Thread',unit:'m',stock:0,manufacturer:'acme',purchase_url:''});
  const image='data:image/png;base64,'+Buffer.from([137,80,78,71,13,10,26,10,0,0,0,0]).toString('base64');
  await service.saveMaterial(first.id,{name:'Paper',unit:'A4',stock:10,expected_stock:10,image});
  const product=await service.saveProduct(null,{name:'Photographed product',recipe:[],image});
  await service.saveProduct(product.id,{name:'Photographed product',recipe:[]});
  assert.equal((await service.overview([])).products.find(p=>p.id===product.id).image,image,'Old clients preserve product images');
  await assert.rejects(service.saveMaterial(first.id,{name:'Paper',unit:'A4',stock:10,expected_stock:10,image:'data:image/svg+xml;base64,PHN2Zz4='}),/image/);
  assert.equal((await service.overview([])).materials.find(m=>m.id===first.id).image,image,'Invalid image does not overwrite saved image');
  await service.saveProduct(product.id,{name:'Photographed product',recipe:[],image:null});
  assert.equal((await service.overview([])).products.find(p=>p.id===product.id).image,null);
  let view=await service.overview([]);
  assert.equal(view.manufacturers.length,1);assert.equal(view.materials.find(m=>m.id===first.id).manufacturer_name,'Acme');
  assert.equal(view.materials.find(m=>m.id===first.id).purchase_url,'https://example.com/paper?a=1&b=2');
  await service.saveMaterial(first.id,{name:'Paper',unit:'A4',stock:10,expected_stock:10});
  assert.equal((await service.overview([])).materials.find(m=>m.id===first.id).manufacturer_name,'Acme','Old clients preserve metadata');
  assert.equal((await service.overview([])).materials.find(m=>m.id===first.id).image,image,'Old clients preserve material images');
  for(const purchase_url of ['javascript:alert(1)','https://user:pass@example.com','bad-url']) await assert.rejects(service.saveMaterial(first.id,{name:'Paper',unit:'A4',stock:10,expected_stock:10,manufacturer:'Bad link maker',purchase_url}),/HTTP/);
  assert.equal((await service.overview([])).manufacturers.length,1,'Failed save rolls back new manufacturer');
  await service.saveShopping(first.id,{quantity:'0.5'});
  await service.saveShopping(first.id,{quantity:'2.5'});
  view=await service.overview([]);assert.equal(view.shopping.length,1);assert.equal(Number(view.shopping[0].quantity),2.5);
  await assert.rejects(service.saveShopping(first.id,{quantity:0}));
  const received=await Promise.allSettled([service.receiveShopping(first.id),service.receiveShopping(first.id)]);
  assert.equal(received.filter(r=>r.status==='fulfilled').length,1);
  view=await service.overview([]);assert.equal(view.shopping.length,0);assert.equal(view.materials.find(m=>m.id===first.id).stock,12.5);
  assert.equal(view.movements.filter(m=>m.reason==='Purchased supplies').length,1);
  await service.saveShopping(second.id,{quantity:1});await service.removeShopping(second.id);
  assert.equal((await service.overview([])).materials.find(m=>m.id===second.id).stock,0);
  await service.saveMaterial(first.id,{name:'Paper',unit:'A4',stock:12.5,expected_stock:12.5,manufacturer:'',purchase_url:''});
  assert.equal((await service.overview([])).materials.find(m=>m.id===first.id).manufacturer_id,null);
  const shortageProduct=await service.saveProduct(null,{name:'Shortage product',recipe:[{material_id:first.id,quantity:0.5},{material_id:second.id,quantity:2}]});
  await service.saveRule(null,{sku:'SHORTAGE',components:[{product_id:shortageProduct.id,quantity:1}]});
  await pool.query("INSERT INTO orders(channel,vendor,external_order_id,skus,raw_skus,workflow_status) VALUES('manual','Test','QUEUE','SHORTAGE',$1,'new'),('manual','Test','DONE','SHORTAGE',$1,'crafted'),('manual','Test','UNMAPPED','unknown','[]','new')",[JSON.stringify([{sku:'SHORTAGE',quantity:30}])]);
  await service.saveShopping(first.id,{quantity:99});
  const beforeMovements=(await service.overview([])).movements.length;
  const bulk=await Promise.all([service.addShoppingShortages(),service.addShoppingShortages()]);
  assert.equal(bulk.reduce((sum,result)=>sum+result.added,0),1,'Concurrent/repeated adds are idempotent');
  assert.equal(bulk[0].unmapped,1);
  view=await service.overview([]);
  assert.equal(Number(view.shopping.find(item=>item.material_id===first.id).quantity),99,'Existing user quantity preserved');
  assert.equal(Number(view.shopping.find(item=>item.material_id===second.id).quantity),60,'Completed orders excluded');
  assert.equal(view.movements.length,beforeMovements,'Shopping additions do not change stock');
  const exported=await require('../src/services/shoppingExport').exportShopping({format:'csv',language:'sk'},pool.query.bind(pool));
  assert(exported.body.toString().includes('"99"'));assert(exported.body.toString().includes('"60"'));assert(exported.body.toString().includes('Paper'));
  assert.deepEqual((await service.overview([])).shopping,view.shopping,'Export must not change shopping quantities');
  await service.removeShopping(first.id);
  assert.equal((await service.addShoppingShortages()).added,1);
  assert.equal(Number((await service.overview([])).shopping.find(item=>item.material_id===first.id).quantity),2.5,'Fractional shortage');
  await service.removeShopping(first.id);await service.removeShopping(second.id);
  const excessive=await service.saveMaterial(null,{name:'ZZ excessive shortage',unit:'m',stock:-1000000000});
  await service.saveProduct(shortageProduct.id,{name:'Shortage product',recipe:[{material_id:first.id,quantity:0.5},{material_id:second.id,quantity:2},{material_id:excessive.id,quantity:1}]});
  await assert.rejects(service.addShoppingShortages(),/quantity/);
  assert.equal((await service.overview([])).shopping.length,0,'Invalid shortage rolls back all earlier additions');
  const receiptKey='00000000-0000-4000-8000-000000000101';
  const receipt={quantity:2.25,expected_quantity:5.5,request_key:receiptKey};
  await service.saveShopping(second.id,{quantity:5.5});
  await Promise.all([service.receiveShopping(second.id,receipt),service.receiveShopping(second.id,receipt)]);
  view=await service.overview([]);
  assert.equal(view.materials.find(m=>m.id===second.id).stock,2.25);
  assert.equal(Number(view.shopping.find(m=>m.material_id===second.id).quantity),3.25);
  await assert.rejects(service.receiveShopping(second.id,{...receipt,quantity:1}),/already used/);
  await assert.rejects(service.receiveShopping(first.id,receipt),/already used/);
  const nextKey='00000000-0000-4000-8000-000000000102';
  await assert.rejects(service.receiveShopping(second.id,{quantity:1,expected_quantity:5.5,request_key:nextKey}),/changed/);
  await assert.rejects(service.receiveShopping(second.id,{quantity:4,expected_quantity:3.25,request_key:nextKey}),/exceed/);
  for(const quantity of [0,-1,'bad']) await assert.rejects(service.receiveShopping(second.id,{quantity,expected_quantity:3.25,request_key:nextKey}));
  const finish={quantity:3.25,expected_quantity:3.25,request_key:nextKey};
  await service.receiveShopping(second.id,finish);await service.receiveShopping(second.id,finish);
  view=await service.overview([]);
  assert.equal(view.materials.find(m=>m.id===second.id).stock,5.5);
  assert.equal(view.shopping.length,0);
  assert.equal(Number((await pool.query('SELECT COUNT(*) FROM inventory_movements WHERE receipt_key IS NOT NULL')).rows[0].count),2);
  await service.saveShopping(second.id,{quantity:4});
  const competing=await Promise.allSettled([103,104].map(n=>service.receiveShopping(second.id,{quantity:2,expected_quantity:4,request_key:`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`})));
  assert.equal(competing.filter(r=>r.status==='fulfilled').length,1);
  view=await service.overview([]);assert.equal(view.materials.find(m=>m.id===second.id).stock,7.5);
  assert.equal(Number(view.shopping[0].quantity),2);
  console.log('Inventory checks passed: manufacturer reuse, link validation/rollback, metadata preservation, shopping updates, fractional receipt, concurrent receipt exactly once, removal and clearing.');
})().catch(error=>{console.error(error.message);process.exitCode=1;}).finally(async()=>{
  if(pool)await pool.end();await original.closePool();
  try{await admin.query(`DROP DATABASE IF EXISTS ${database}`);}finally{await admin.end();}
});

const assert = require('assert/strict');
const { validatePins, countPins, matchesSku } = require('../src/services/dashboardPins');
const pins = validatePins([{name:'Custom item',skus:['ABC','SET-*']}]);
assert.equal(matchesSku('ABCD','ABC'),false);
assert.equal(matchesSku('abc','ABC'),true);
assert.equal(matchesSku('SET-blue','SET-*'),true);
assert.equal(matchesSku('ABCx','ABC.'),false);
const order = {workflow_status:'new',shipped:false,raw_skus:[{sku:'ABC',quantity:3},{sku:'SET-blue',quantity:2}]};
assert.equal(countPins(pins,[order])[0].count,5);
for(const status of ['crafted','ready_for_pickup','shipped']) assert.equal(countPins(pins,[{...order,workflow_status:status}])[0].count,0);
assert.equal(countPins(pins,[{...order,shipped:true}])[0].count,0);
assert.equal(countPins([{name:'Legacy',skus:['*gobbigreen*'],preparedColor:'green'}],[{skus:'GobbiGreen',prepared_gobbis:['green']}])[0].count,0);
assert.equal(countPins([{name:'No double counting',skus:['ABC','A*']}],[order])[0].count,3);
assert.deepEqual(validatePins([]),[]);
for(const value of [{},[{name:'',skus:['ABC']}],[{name:'Bad',skus:['*']}],[{name:'Bad',skus:[]}]]) assert.throws(()=>validatePins(value));
assert.equal(countPins(pins,[{skus:'ABC x3 + SET-blue x2',raw_skus:[]}])[0].count,5);
assert.equal(countPins(pins,[{...order,skus:'ABC x3 + SET-blue x2'}])[0].count,5);
assert.equal(countPins(pins,[{...order,skus:'OTHER',skus_locked:true}])[0].count,0);
console.log('Pinned SKU validation, quantities, wildcard matching and crafting exclusions passed');

'use strict';
const assert=require('node:assert/strict');
const {normalize,fromGross,rate}=require('../src/services/vat');
const {orderCost}=require('../src/services/costMath');
const {summarize}=require('../src/services/profitability');
assert.equal(fromGross('89','23').vat,'16.642276');assert.equal(fromGross('89','23').net,'72.357724');
assert.deepEqual(fromGross('100','0'),{net:'100.000000',vat:'0.000000'});assert.equal(rate('19,5'),19.5);
for(const r of [-1,101,'bad','23.123'])assert.throws(()=>rate(r));
assert.throws(()=>normalize({mode:'artist',costs_include_vat:true}));
const vat=normalize({mode:'payer',rate:20,costs_include_vat:true,revenue_vat:20,deductible_vat:10});
const order={channel:'manual',profit_month:'2026-10',revenue_amount:'120',revenue_currency:'EUR'};
const production={amount:'60',currency:'EUR',missing:[],products:[]};
const entered={vat,currency:'EUR',shipping_cost:'0',marketplace_fee:'0',payment_fee:'0',other_cost:'0'};
let cost=orderCost(order,production,entered,true);assert.equal(cost.revenue,'100.000000');assert.equal(cost.total,'50.000000');assert.equal(cost.profit,'50.000000');assert.equal(cost.margin_percent,50);
assert.equal(orderCost(order,production,{...entered,vat:{mode:'nonpayer'}},true).profit,'60.000000');
assert.equal(orderCost(order,production,{...entered,vat:null},true).profit,'60.000000');
assert.equal(orderCost(order,production,{...entered,vat:{...vat,revenue_vat:null}},true).profit,null);
assert.equal(orderCost(order,production,{...entered,vat:{...vat,deductible_vat:'61'}},true).profit,null);
assert.equal(orderCost(order,production,{...entered,vat:{...vat,revenue_vat:'121'}},true).profit,null);
assert.equal(normalize({...vat,costs_include_vat:false,deductible_vat:10}).deductible_vat,'0.000000');
assert.equal(normalize({mode:'nonpayer',costs_include_vat:true,rate:23,revenue_vat:20,deductible_vat:10}).revenue_vat,undefined);
const base={...order,...entered,entered_currency:'EUR',consumed:true,cost_snapshot:production};
const result=summarize([base,{...base,vat:{mode:'nonpayer'}}],{});assert.equal(result.totals.length,2,'Different VAT treatments are never silently combined');assert.deepEqual(result.totals.map(r=>r.profit),['50.000000','60.000000']);
console.log('PASS VAT: own rates, exact gross conversion, payer/nonpayer, missing/excess VAT, net costs, explicit treatment and separate report bases');
